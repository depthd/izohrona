def план(куда, X0, X1, Y0, Y1, заголовок, строки, K=0.52):
    """План сверху по ТЕМ ЖЕ следам, что ушли в файл."""
    from PIL import Image, ImageDraw, ImageFont
    ВЕРХ, П = 156, 26
    ш, в = int((X1 - X0) * K), int((Y1 - Y0) * K)
    im = Image.new('RGB', (max(ш + П * 2, 980), в + ВЕРХ + П), (14, 14, 18))
    d = ImageDraw.Draw(im)

    def экр(p):
        return (П + (p[0] - X0) * K, ВЕРХ + (Y1 - p[1]) * K)
    for точки, z0, z1, mat, прав in СЛЕДЫ:
        if mat == НЕБО:
            continue
        if mat == ДОСКИ:
            c = (150, 116, 74)
        elif mat == КАМЕНЬ:
            c = (170, 170, 165)
        elif mat.startswith(ПОЛ):
            c = ЦВЕТА.get(mat[len(ПОЛ):], (110, 110, 110))
        else:
            c = (232, 196, 150) if z1 - z0 > 12 else (60, 56, 52)
        d.polygon([экр(p) for p in точки], fill=c)
    ш1 = '/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf'
    ш2 = '/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf'
    f1, f3 = ImageFont.truetype(ш1, 32), ImageFont.truetype(ш2, 20)
    d.text((П, 16), заголовок, fill=(240, 240, 242), font=f1)
    for i, стр in enumerate(строки):
        d.text((П, 58 + i * 26), стр, fill=(150, 155, 165), font=f3)
    im.save(куда)
    print('  план:', куда, im.size, file=sys.stderr)
