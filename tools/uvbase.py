"""ОБЩЕЕ ДЛЯ ЛАБОРАТОРИЙ ТЕКСТУР: тела, правила наложения, самопроверка, план.

Вынесено из uvlab2 после третьей лаборатории: копия расходится с оригиналом
через две правки, а тут правила наложения — то самое, что уедет в продукт.
Один файл на все опыты, чтобы «правило» значило одно и то же везде.

ПРАВИЛА НАЛОЖЕНИЯ (по РОЛИ грани, а не по её размеру):

  Ф   одна картинка ровно на грань; грань короче МИН_ФИТ уходит в Н.
      Предмет: ящик, контейнер, бочка — то, что читается одной вещью.
  Ф0  то же, но жмёт всегда. Только чтобы показать, во что превращается
      торец в 8 юнитов.
  П   ближайшее целое число картинок к натуральному размеру, швы на ОБОИХ
      рёбрах. Длинная стенка, помост, крыша, высокий столб.
  Н   повтор ровно НАТ юнитов, шов на ближнем ребре. Трим и торцы.
  М   повтор НАТ юнитов, БЕЗ своего шва — общая сетка мира. Нужен там, где
      несколько тел образуют одну поверхность: буква из плиток, пол, нарезанный
      жадным мешером. С правилом Н каждая плитка получает один и тот же кусок
      картинки, и буква читается как мозаика из одинаковых штампов.

ЧТО ПОДТВЕРЖДЕНО ЖИВЫМ ЧЕЛОВЕКОМ (uvlab.py, семь площадок в CS2):
импортёр делит скейл .vmf на 16; в cs_italy/picrate1 256 текселей; шов обязан
садиться на ребро; вертикальный переворот боковин на этой текстуре не виден.
"""
import math
import sys

КРБ = "cs_italy/picrate1"
ПОЛ = "concrete/hr_c/hr_concrete_wall_painted_001_"
ДОСКИ = "anubis/anubis_wood_planks01"
КАМЕНЬ = "de_anubis/models/structures/stones_single"
НЕБО = "TOOLS/TOOLSSKYBOX"
IMP = 16          # подтверждено: импортёр делит скейл .vmf на столько
НАТ = 96          # натуральный повтор картинки ящика в юнитах
МИН_ФИТ = 24      # грань короче — жать картинку нечего, там правило Н

_id = [0]
ПРОВЕРКА = []     # грани и их оси — для пересчёта «куда легла картинка»
СЛЕДЫ = []        # следы тел — чтобы план рисовался тем же, что ушло в файл


def nid():
    _id[0] += 1
    return _id[0]


def г(v):
    return f'{round(v, 4):g}'


def ось(вект, начало, длина, правило):
    """uaxis/vaxis для одной оси грани.
    вект — единичное направление в мире; начало — координата ЭТОГО ЖЕ вектора
    в том углу грани, откуда должна начаться картинка; длина — сколько юнитов
    грань занимает вдоль вектора.
    Тексель считается как (точка · вект)/скейл + смещение, значит картинка
    начинается там, где (точка · вект) = -смещение·скейл. Отсюда смещение."""
    if правило == 'Ф0' or (правило == 'Ф' and длина >= МИН_ФИТ):
        sc = длина / IMP                       # ровно одна картинка на длину
    elif правило == 'П' and длина >= МИН_ФИТ:
        n = max(1, round(длина / НАТ))
        sc = длина / (IMP * n)                 # целое число картинок, швы на рёбрах
    else:
        sc = НАТ / IMP                         # натуральный размер
    off = 0 if правило == 'М' else -начало / sc
    # Ось и смещение печатаются подробнее, чем координаты: у повёрнутого тела
    # компонента оси домножается на координату порядка тысячи, и округление до
    # четырёх знаков уводило шов на сотые доли текселя. Самопроверка это увидела
    # (64 грани со стартом 0.007 вместо нуля) — глазом бы не поймал никогда.
    v = ' '.join(f'{c:.9g}' for c in вект)
    return f'[{v} {off:.9g}] {sc:.9g}'


def разбор(ось_):
    ч = ось_.strip('[').split(']')
    вект = [float(x) for x in ч[0].split()[:3]]
    сдвиг = float(ч[0].split()[3])
    скейл = float(ч[1])
    return вект, сдвиг, скейл


def side(p1, p2, p3, mat, u, v):
    return (f'\t\tside\n\t\t{{\n\t\t"id" "{nid()}"\n'
            f'\t\t"plane" "({p1}) ({p2}) ({p3})"\n'
            f'\t\t"material" "{mat}"\n'
            f'\t\t"uaxis" "{u}"\n\t\t"vaxis" "{v}"\n'
            f'\t\t"rotation" "0"\n\t\t"lightmapscale" "16"\n'
            f'\t\t"smoothing_groups" "0"\n\t\t}}')


def т(p):
    return ' '.join(г(c) for c in p)


def призма(точки, z0, z1, mat, правило, цвет="255 130 40"):
    """Выпуклая призма по следу (точки против часовой стрелки, вид сверху).
    Одним куском покрывает и осевой ящик, и повёрнутый, и восьмигранную бочку —
    поэтому поворот не отдельный случай в коде, а тот же самый.
    Ориентация плоскостей проверена на осевой коробке из tools/uvruler.py:
    нормаль = (p1-p2) x (p3-p2), и все грани смотрят наружу."""
    n = len(точки)
    гр = []
    # верх и низ: оси идут вдоль первого ребра следа, чтобы у повёрнутого тела
    # картинка поворачивалась вместе с ним, а не оставалась по миру
    ex = (точки[1][0] - точки[0][0], точки[1][1] - точки[0][1])
    Lu = math.hypot(*ex)
    ux, uy = ex[0] / Lu, ex[1] / Lu
    vx, vy = uy, -ux                            # у осевой коробки это (0,-1)
    # Шов садится на КРАЙ следа, а не на первый попавшийся угол. Первая редакция
    # брала точку отсчёта из точки[0]; у осевой коробки она случайно совпадала с
    # краем по u, но по v лежала на противоположной стороне, и у 229 граней из 756
    # картинка начиналась не с нуля. Самопроверка это и поймала.
    пU = [p[0] * ux + p[1] * uy for p in точки]
    пV = [p[0] * vx + p[1] * vy for p in точки]
    начU, размахU = min(пU), max(пU) - min(пU)
    начV, размахV = min(пV), max(пV) - min(пV)
    uТ = ось((ux, uy, 0), начU, размахU or Lu, правило)
    vТ = ось((vx, vy, 0), начV, размахV or Lu, правило)
    гр.append(side(т((*точки[2], z1)), т((*точки[1], z1)), т((*точки[0], z1)), mat, uТ, vТ))
    гр.append(side(т((*точки[0], z0)), т((*точки[1], z0)), т((*точки[2], z0)), mat, uТ, vТ))
    ПРОВЕРКА.append(('верх', правило, [(*p, z1) for p in точки], uТ, vТ))
    # боковины: своя ось на каждое ребро, поэтому поворот учтён сам собой
    for i in range(n):
        a, b = точки[i], точки[(i + 1) % n]
        L = math.hypot(b[0] - a[0], b[1] - a[1])
        if L < 1e-6:
            continue
        ex, ey = (b[0] - a[0]) / L, (b[1] - a[1]) / L
        u = ось((ex, ey, 0), a[0] * ex + a[1] * ey, L, правило)
        v = ось((0, 0, -1), -z1, z1 - z0, правило)   # вниз от верхней кромки
        гр.append(side(т((*b, z0)), т((*a, z0)), т((*a, z1)), mat, u, v))
        ПРОВЕРКА.append(('бок', правило, [(*a, z0), (*b, z0), (*b, z1), (*a, z1)], u, v))
    СЛЕДЫ.append((list(точки), z0, z1, mat, правило))
    return ('\tsolid\n\t{\n\t"id" "%d"\n' % nid()) + '\n'.join(гр) + \
           f'\n\t\teditor {{ "color" "{цвет}" }}\n\t}}'


def ящик(x, y, w, h, z0, z1, mat, правило, поворот=0, цвет="255 130 40"):
    """Осевой или повёрнутый ящик: след строится один раз, дальше общая призма."""
    cx, cy = x + w / 2, y + h / 2
    a = math.radians(поворот)
    ca, sa = math.cos(a), math.sin(a)
    углы = []
    for dx, dy in ((-w / 2, -h / 2), (w / 2, -h / 2), (w / 2, h / 2), (-w / 2, h / 2)):
        углы.append((cx + dx * ca - dy * sa, cy + dx * sa + dy * ca))
    return призма(углы, z0, z1, mat, правило, цвет)


def бочка(cx, cy, r, z0, z1, mat, правило, цвет="220 160 60"):
    """Восьмигранник: восемь боковин, у каждой своя ось. Проверка, что правило
    не разваливается там, где граней не четыре и они не по осям."""
    углы = [(cx + r * math.cos(math.pi / 8 + k * math.pi / 4),
             cy + r * math.sin(math.pi / 8 + k * math.pi / 4)) for k in range(8)]
    return призма(углы, z0, z1, mat, правило, цвет)


ШРИФТ = {
    1: ("010", "110", "010", "010", "111"), 2: ("111", "001", "111", "100", "111"),
    3: ("111", "001", "111", "001", "111"), 4: ("101", "101", "111", "001", "001"),
    5: ("111", "100", "111", "001", "111"), 6: ("111", "100", "111", "101", "111"),
    7: ("111", "001", "010", "010", "010"), 8: ("111", "101", "111", "101", "111"),
}
КЛ = 32


def цифра(n, x, y, out, правило='М', mat=КРБ, слить=False, толщ=8):
    """Цифра из плиток. Если слить — соседние клетки ряда идут одним брашем:
    внутри куска картинка непрерывна по построению, швов между плитками нет."""
    for r, ряд in enumerate(ШРИФТ[n]):
        c = 0
        while c < 3:
            if ряд[c] != '1':
                c += 1
                continue
            k = c
            while слить and k + 1 < 3 and ряд[k + 1] == '1':
                k += 1
            out.append(ящик(x + c * КЛ, y - (r + 1) * КЛ, (k - c + 1) * КЛ, КЛ,
                            0, толщ, mat, правило, 0, "255 220 60"))
            c = k + 1


