        повт = прав == 'П' and длина >= МИН_ФИТ
        ok = abs(нач) < 1e-3 and (
            abs(плиток - 1) < 1e-3 if фит
            else abs(плиток - round(плиток)) < 1e-3 if повт
            else abs(скейл - НАТ / IMP) < 1e-6)
        if not ok:
            бед.append((что, прав, имя, round(нач, 3), round(плиток, 3)))
