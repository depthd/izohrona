"""ЛАБОРАТОРИЯ 3: МЕЛОЧЬ И СТОЛБЫ. Две вещи, которые он забраковал на второй.

ЕГО ВЕРДИКТ ПО ВТОРОЙ ЛАБОРАТОРИИ: «всё великолепно кроме мелких структур типа
букв на полу или столбов. Но я подозреваю что здесь не твоя вина, а нюансы
сетки. Нет?»

НЕТ, НЕ СЕТКИ. Посчитал — это две разные болезни, и первая целиком моя.

БУКВА ИЗ ПЛИТОК. Правило Н сажает шов на ребро КАЖДОГО куска. Плитка 32u берёт
ровно треть картинки, и берёт КАЖДЫЙ РАЗ ОДНУ И ТУ ЖЕ треть — от нуля. Отсюда
у каждой плитки своя рамка ящика, и буква читается мозаикой из одинаковых
штампов, а не куском поверхности. Лечится двумя вещами:
  общей сеткой мира (правило М) — рисунок продолжается с куска на кусок;
  слиянием соседних клеток в один браш — внутри куска швов нет вовсе.

СТОЛБ 24x24x152. Тут сетка ни при чём, и правило тоже не главное. По высоте
натуральный повтор в 96u укладывается 1.58 раза — шов повисает посреди столба
в 56 юнитах от низа, и это видно как поперечная полоса. Целые повторы (2 по
76u) убирают полосу с середины на торцы. Но остаётся второе, и оно важнее:
на грани шириной 24 юнита помещается ЧЕТВЕРТЬ картинки ящика. Картинка ящика
на столбе не будет выглядеть правильно ни при каком наложении — столбу нужен
другой материал. Это уже не «нюанс сетки», а неправильно выбранная текстура.

ПЛОЩАДКИ (пол своего цвета, цифра у левого края сделана правилом своей же
площадки — то есть цифра сама и есть опыт):

  1 красный    буквы как во второй лаборатории: шов на ребре каждой плитки
  2 оранжевый  буквы на общей сетке мира
  3 жёлтый     буквы слитыми кусками + общая сетка          <- жду, что лучшее
  4 зелёный    столбы как во второй: натуральный повтор, шов посреди
  5 синий      столбы целыми повторами: швы только на торцах
  6 белый      столбы досками вместо картинки ящика         <- жду, что лучшее

    python3 tools/uvlab3.py [--png план.png] > /tmp/uvlab3.vmf
"""
import sys

sys.path.insert(0, 'tools')
from uvbase import (КРБ, ПОЛ, ДОСКИ, КАМЕНЬ, НАТ, ящик, цифра, карта,
                    самопроверка, план)

ПЛОЩ_Y = 448
ШАГ_Y = 576
ЦИФРА_X = -224
ШИР = 1280


def буквы(x0, y0, правило, слить, out):
    """Строка из плиток: 1234 подряд, чтобы разрыв рисунка между кусками был
    виден не на одной плитке, а на длинной строке."""
    for k, n in enumerate((1, 2, 3, 4)):
        цифра(n, x0 + k * 160, y0 + ПЛОЩ_Y - 96, out, правило, КРБ, слить)
    # плюс сплошная полоса из плиток 32u — самый честный тест непрерывности
    for k in range(12):
        out.append(ящик(x0 + 704 + k * 32, y0 + 96, 32, 96, 0, 8, КРБ,
                        правило, 0, "255 220 60"))
    # и та же полоса одним куском — эталон, как должно выглядеть
    out.append(ящик(x0 + 704, y0 + 224, 384, 96, 0, 8, КРБ, правило, 0, "120 255 120"))


def столбы(x0, y0, правило, mat, out):
    """Четыре стойки разной высоты плюс балка сверху: столб редко стоит один."""
    x = x0
    for h in (96, 128, 152, 192):
        out.append(ящик(x, y0 + 160, 24, 24, 0, h, mat, правило))
        x += 128
    out.append(ящик(x0, y0 + 160, x - x0 - 104, 24, 192, 216, mat, правило))
    # рядом — те же стойки потолще, чтобы было видно, где начинается «нормально»
    x += 64
    for w in (32, 48, 64, 96):
        out.append(ящик(x, y0 + 160, w, w, 0, 152, mat, правило))
        x += w + 96
    return x


ПЛОЩАДКИ = [
    ('красный',   'red',        'буквы: шов на ребре каждой плитки (как было)',
     lambda x, y, o: буквы(x, y, 'Н', False, o)),
    ('оранжевый', 'orange',     'буквы: общая сетка мира',
     lambda x, y, o: буквы(x, y, 'М', False, o)),
    ('жёлтый',    'yellow',     'буквы: слитые куски + общая сетка',
     lambda x, y, o: буквы(x, y, 'М', True, o)),
    ('зелёный',   'green',      'столбы: натуральный повтор (как было)',
     lambda x, y, o: столбы(x, y, 'Н', КРБ, o)),
    ('синий',     'blue',       'столбы: целые повторы, швы на торцах',
     lambda x, y, o: столбы(x, y, 'П', КРБ, o)),
    ('белый',     'grey_warm',  'столбы: доски вместо картинки ящика',
     lambda x, y, o: столбы(x, y, 'П', ДОСКИ, o)),
]

solids = []
легенда = []
for k, (цвет, суф, что, стройка) in enumerate(ПЛОЩАДКИ):
    y0 = k * ШАГ_Y
    solids.append(ящик(-320, y0, ШИР + 320, ПЛОЩ_Y, -32, 0, ПОЛ + суф, 'М', 0, "120 120 120"))
    # номер площадки — камнем и общей сеткой, чтобы он читался на любой площадке
    цифра(k + 1, ЦИФРА_X, y0 + ПЛОЩ_Y - 48, solids, 'М', КАМЕНЬ, True)
    стройка(64, y0, solids)
    легенда.append(f'  {k+1}. пол {цвет:10s} — {что}')

ВЫС = 640
X0, X1 = -448, ШИР + 192
Y0, Y1 = -128, len(ПЛОЩАДКИ) * ШАГ_Y + 128
print(карта(solids, X0, X1, Y0, Y1, ВЫС,
            ' | '.join(f'{i+1} {c} = {w}' for i, (c, _, w, _) in enumerate(ПЛОЩАДКИ)),
            спавнX=ЦИФРА_X - 96))
самопроверка()
if '--png' in sys.argv:
    план(sys.argv[sys.argv.index('--png') + 1], X0, X1, Y0, Y1,
         'Лаборатория 3: буквы на полу и столбы.',
         ('Площадки 1 и 4 — как было. 2, 3, 5, 6 — что я предлагаю вместо.',
          'Тёмное — плитки букв, светлое — стойки и балка.',
          'Цифра площадки сделана правилом «общая сетка», камнем.'))
print('ЛАБОРАТОРИЯ 3 — МЕЛОЧЬ И СТОЛБЫ\n' + '\n'.join(легенда)
      + f'\n  Н натуральный {НАТ}u со своим швом · М та же плотность, общая сетка'
      + '\n  П целое число картинок, швы на торцах', file=sys.stderr)
