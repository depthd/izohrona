# ВСЯ РАМА ВЫВОДИТСЯ ИЗ ОДНОГО ЧИСЛА. Его сборка при ящике 96 даёт вылет рейки 4,
# вылет угла 8, свес верхнего пояса 8, отступ рейки внутрь 8, толщину рейки 12 и
# угловой блок 16. Это в точности a, 2a, 2a, 2a, 3a, 4a при a=4, то есть a = 96/24.
# Отсюда пропорциональная рама: a считается от размера ящика, соотношение рамы к
# телу держится одинаковым и на маленьком, и на большом.
БАЗА = 24         # ящик такого размера получает раму в один юнит
A_МИН, A_МАКС = 2, 16   # тоньше двух — не рама, а невидимая плёнка для рендера


def мераРамы(w, h, H, постоянная=False):
    """-> (a, Т, У, ВР, ВУ, И, НИЗ). Считается от МЕНЬШЕЙ стороны: она и
    ограничивает, и по ней глаз оценивает пропорцию.
    Проверка на заведомо известном: при 96x96x96 обязана выйти его сборка."""
    a = 4 if постоянная else max(A_МИН, min(A_МАКС, round(min(w, h, H) / БАЗА)))
    return a, 3 * a, 4 * a, a, 2 * a, 2 * a, 2 * a


def крутойящик(x, y, w, h, z0, z1, панель, рама, out, постоянная=False):
    """Ящик с бортами ровно по его схеме, рама пропорциональна телу.

    ВЕРХ И НИЗ РАЗНЫЕ, И ЭТО ГЛАВНОЕ. Сверху над ящиком есть воздух, поэтому
    верхний пояс СВИСАЕТ внутрь и торчит наружу вверх: рейка на a, угловой блок
    на 2a. Снизу пол, и торчать вниз нельзя — там появится геометрия, которую
    никто никогда не увидит, но которую движок посчитает. Поэтому нижний пояс
    ровно 3a высотой, от пола, и ничего вниз не выступает.

    Пропорциональная рама вдобавок не может развалиться по построению: рейке
    нужно w > 4a, стойке H > 5a, а a не больше меньшей стороны, делённой на 24."""
    a, Т, У, ВР, ВУ, И, НИЗ = мераРамы(w, h, z1 - z0, постоянная)
    out.append(ящик(x, y, w, h, z0, z1, панель, 'Ф'))
    if min(w, h) < 2 * И + Т or (z1 - z0) < Т + НИЗ + Т:
        return                                   # только у постоянной рамы и мелкого тела
    низ = (z0, z0 + Т)                           # нижний пояс: от пола, заподлицо
    верхР = (z1 - НИЗ, z1 - НИЗ + Т)             # верхняя рейка: торчит на a
    верхУ = (z1 - НИЗ, z1 - НИЗ + У)             # верхний угол: торчит на 2a
    # Вылет мерится ОТ СВОЕЙ ГРАНИ, поэтому на дальней стороне начало другое.
    # Первая сверка с его ящиком: 14 кусков из 21 совпали, а семь уехали ровно на
    # дальних гранях — я там вычитал вылет вместо того, чтобы вычитать остаток.
    def нач(c, дальний, толщ, выл):
        return (c + выл - толщ) if дальний else (c - выл)
    углы = ((x, y, False, False), (x + w, y, True, False),
            (x + w, y + h, True, True), (x, y + h, False, True))
    for (cx, cy, дх, ду) in углы:                # угловые блоки: по центру ребра
        for (za, zb) in (низ, верхУ):
            out.append(ящик(нач(cx, дх, У, ВУ), нач(cy, ду, У, ВУ), У, У,
                            za, zb, рама, 'М', 0, "120 200 255"))
    for cy, ду in ((y, False), (y + h, True)):   # рейки вдоль X
        for (za, zb) in (низ, верхР):
            out.append(ящик(x + И, нач(cy, ду, Т, ВР), w - 2 * И, Т,
                            za, zb, рама, 'М', 0, "120 200 255"))
    for cx, дх in ((x, False), (x + w, True)):   # рейки вдоль Y
        for (za, zb) in (низ, верхР):
            out.append(ящик(нач(cx, дх, Т, ВР), y + И, Т, h - 2 * И,
                            za, zb, рама, 'М', 0, "120 200 255"))
    for (cx, cy, дх, ду) in углы:                # стойки между поясами
        out.append(ящик(нач(cx, дх, Т, ВР), нач(cy, ду, Т, ВР), Т, Т,
                        z0 + Т, z1 - НИЗ, рама, 'М', 0, "120 200 255"))


def ряд(x0, y0, панель, рама, out, постоянная=False):
    """От самого маленького до большого: на этом ряду и видно, держится ли
    соотношение рамы к телу."""
    x = x0
    for (w, h, hz) in ((32, 32, 32), (48, 48, 40), (64, 64, 64), (96, 96, 96),
                       (96, 96, 40), (192, 192, 96), (128, 96, 112)):
        крутойящик(x, y0 + (ПЛОЩ_Y - h) // 2, w, h, 0, hz, панель, рама, out, постоянная)
        x += w + 128
    return x


