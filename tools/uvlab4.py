"""ЛАБОРАТОРИЯ 4: ЯЩИК С БОРТАМИ. Рама по рёбрам, панели внутри, разные текстуры.

ОТКУДА СХЕМА. Он собрал такой ящик руками (krutoyyashik.vmap) — 21 кусок,
и я разобрал их по габаритам:

  ядро          96 x 96 x 96
  угловой блок  16 x 16, восемь штук: четыре сверху, четыре снизу,
                посажен ПО ЦЕНТРУ ребра — 8 юнитов наружу, 8 внутрь
  рейка         12 x 80, восемь штук: по две на каждое горизонтальное ребро,
                4 юнита наружу, 8 внутрь, длиной между угловыми блоками
  стойка        12 x 12, четыре штуки в углах, между верхней и нижней рейкой

Всё вместе даёт габарит 112 x 112: рама выступает за ядро. Схема
параметризована — размер, толщина рамы и вылет считаются от габарита ящика,
поэтому она одинаково собирается и на кубе 96, и на низком 96x96x64, и на
большом 192.

ОДНО ОТЛИЧИЕ ОТ ЕГО СБОРКИ, И ОНО НАРОЧНОЕ. У него верхняя рейка выступает на
4 юнита ВЫШЕ ядра, а угловой блок ещё выше. На тестовой карте это неважно, на
боевой — важно: высота укрытия решает, простреливают тебя или нет, и растр про
эти лишние юниты не знает. Поэтому по вертикали рама заподлицо: наружу она
выступает только вбок.

ТЕКСТУРЫ. Панель — картинка ящика, правило «одна картинка на грань». Рама —
другой материал и общая сетка мира, без подгонки: он прямо сказал, что на
мелочь вроде реек не надо велосипедов с масштабами, нужна обычная текстура.

Шесть площадок — шесть пар «рама / панель». Задача человека: сказать, какая
пара выглядит как настоящий ящик.

    python3 tools/uvlab4.py [--png план.png] > /tmp/uvlab4.vmf
"""
import sys

sys.path.insert(0, 'tools')
from uvbase import (КРБ, ПОЛ, ДОСКИ, КАМЕНЬ, ящик, цифра, карта,
                    самопроверка, план)

МЕТАЛЛ = "models/props/de_mirage/wall_hole/sheet_metal_panel"
ЯЩИК2 = "models/props/de_nuke/crate"
ДОСКА2 = "anubis/models/market/wood_planks_4"

ПЛОЩ_Y = 512
ШАГ_Y = 640
ЦИФРА_X = -224
ШИР = 1280


def крутойящик(x, y, w, h, z0, z1, панель, рама, out,
               У=16, Т=12, ВУ=8, ВР=4, И=8):
    """Ящик с бортами. У — угловой блок, Т — толщина рейки и стойки,
    ВУ и ВР — насколько блок и рейка торчат наружу, И — насколько внутрь."""
    H = z1 - z0
    out.append(ящик(x, y, w, h, z0, z1, панель, 'Ф'))
    if min(w, h) < 4 * И or H < 3 * Т:
        return                                   # мелкому ящику рама не влезает
    углы = ((x, y), (x + w, y), (x + w, y + h), (x, y + h))
    ярусы = ((z0, z0 + Т), (z1 - Т, z1))         # заподлицо по вертикали, см. шапку
    for (cx, cy) in углы:
        for (za, zb) in ярусы:
            out.append(ящик(cx - ВУ, cy - ВУ, У, У, za, zb, рама, 'М', 0, "120 200 255"))
    for cy in (y, y + h):                        # рейки вдоль X
        for (za, zb) in ярусы:
            out.append(ящик(x + И, cy - ВР, w - 2 * И, Т, za, zb, рама, 'М', 0, "120 200 255"))
    for cx in (x, x + w):                        # рейки вдоль Y
        for (za, zb) in ярусы:
            out.append(ящик(cx - ВР, y + И, Т, h - 2 * И, za, zb, рама, 'М', 0, "120 200 255"))
    for (cx, cy) in углы:                        # стойки между рейками
        out.append(ящик(cx - ВР, cy - ВР, Т, Т, z0 + Т, z1 - Т, рама, 'М', 0, "120 200 255"))


def ряд(x0, y0, панель, рама, out):
    """Четыре ящика: куб, низкий боевой, большой и вытянутый."""
    x = x0
    for (w, h, hz) in ((96, 96, 96), (96, 96, 64), (192, 192, 96), (128, 96, 112)):
        крутойящик(x, y0 + (ПЛОЩ_Y - h) // 2, w, h, 0, hz, панель, рама, out)
        x += w + 128
    return x


ПЛОЩАДКИ = [
    ('красный',   'red',        'рама металл / панель ящик',      МЕТАЛЛ, КРБ),
    ('оранжевый', 'orange',     'рама камень / панель ящик',      КАМЕНЬ, КРБ),
    ('жёлтый',    'yellow',     'рама доски / панель ящик',       ДОСКИ,  КРБ),
    ('зелёный',   'green',      'рама металл / панель доски',     МЕТАЛЛ, ДОСКА2),
    ('синий',     'blue',       'рама ящик / панель другой ящик', КРБ,    ЯЩИК2),
    ('белый',     'grey_warm',  'всё одним материалом (контроль)', КРБ,   КРБ),
]

solids = []
легенда = []
for k, (цвет, суф, что, рама, панель) in enumerate(ПЛОЩАДКИ):
    y0 = k * ШАГ_Y
    solids.append(ящик(-320, y0, ШИР + 320, ПЛОЩ_Y, -32, 0, ПОЛ + суф, 'М', 0, "120 120 120"))
    цифра(k + 1, ЦИФРА_X, y0 + ПЛОЩ_Y - 48, solids, 'М', КАМЕНЬ, True)
    ряд(64, y0, панель, рама, solids)
    легенда.append(f'  {k+1}. пол {цвет:10s} — {что}')

ВЫС = 640
X0, X1 = -448, ШИР + 192
Y0, Y1 = -128, len(ПЛОЩАДКИ) * ШАГ_Y + 128
print(карта(solids, X0, X1, Y0, Y1, ВЫС,
            ' | '.join(f'{i+1} {c} = {w}' for i, (c, _, w, _, _) in enumerate(ПЛОЩАДКИ)),
            спавнX=ЦИФРА_X - 96))
самопроверка()
if '--png' in sys.argv:
    план(sys.argv[sys.argv.index('--png') + 1], X0, X1, Y0, Y1,
         'Лаборатория 4: ящик с бортами.',
         ('Схема снята с твоего ящика: ядро, восемь угловых блоков, восемь реек, четыре стойки.',
          'Голубое — рама, светлое — панель. Шесть площадок — шесть пар материалов.',
          'По вертикали рама заподлицо: высота укрытия не должна расти от декора.'),
         K=0.46)
print('ЛАБОРАТОРИЯ 4 — ЯЩИК С БОРТАМИ\n' + '\n'.join(легенда)
      + f'\n  на площадку 4 ящика: куб 96, низкий 96x96x64, большой 192, вытянутый 128x96x112',
      file=sys.stderr)
