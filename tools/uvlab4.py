"""ЛАБОРАТОРИЯ 4: ЯЩИК С БОРТАМИ. Рама по рёбрам, панели внутри, разные текстуры.

ОТКУДА СХЕМА. Он собрал такой ящик руками (krutoyyashik.vmap) — 21 кусок,
и я разобрал их по габаритам:

  ядро          96 x 96 x 96
  угловой блок  16 x 16, восемь штук: четыре сверху, четыре снизу,
                посажен ПО ЦЕНТРУ ребра — 8 юнитов наружу, 8 внутрь
  рейка         12 x 80, восемь штук: по две на каждое горизонтальное ребро,
                4 юнита наружу, 8 внутрь, длиной между угловыми блоками
  стойка        12 x 12, четыре штуки в углах, между верхней и нижней рейкой

Всё вместе даёт габарит 112 x 112: рама выступает за ядро. Схема
параметризована — размер, толщина рамы и вылет считаются от габарита ящика,
поэтому она одинаково собирается и на кубе 96, и на низком 96x96x64, и на
большом 192.

ВЕРХ И НИЗ РАЗНЫЕ, И ЭТО ГЛАВНОЕ В СХЕМЕ. Сверху над ящиком воздух, поэтому
верхний пояс свисает на 8 внутрь и торчит наружу вверх: рейка на 4, угловой блок
на 8. Снизу пол, и торчать вниз нельзя — там появилась бы геометрия, которую
никто не увидит, а движок посчитает. Поэтому нижний пояс ровно 12 от пола и
ничего вниз не выступает.

Прошлая моя версия делала оба пояса заподлицо, «чтобы высота укрытия не росла».
Получилось плохо: угловые кубики торчали вбок ни к чему не привязанные, а боковая
грань ядра спорила с рамой, потому что сверху её ничто не перекрывало. Высоту
укрытия правильнее вычесть при расстановке, а не ломать ради неё вид.

СВЕРКА С ЭТАЛОНОМ. Собранный здесь ящик 96 сравнивается с его файлом кусок в
кусок по координатам: 21 из 21 совпадает. Первый заход дал 14 из 21 — вылет на
ДАЛЬНИХ гранях я отсчитывал не с той стороны, и рейка уезжала на 4 юнита внутрь
вместо наружу. Глазом на плане это неразличимо, сверкой видно сразу.

РАМА ПРОПОРЦИОНАЛЬНА ТЕЛУ. Вся она выводится из ОДНОГО числа a: вылет рейки a,
вылет угла 2a, свес верхнего пояса 2a, отступ рейки внутрь 2a, толщина рейки 3a,
угловой блок 4a. При a=4 это в точности его сборка, а 4 = 96/24 — значит
a = меньшая сторона / 24, и соотношение рамы к телу держится одинаковым.

Замер по размерам: доля рейки от меньшей стороны 11.7–15% на всём диапазоне от
48 до 256, при 12.5% у эталона. Выпадают только 24 и 32: там a упирается в
нижний предел 2, потому что рейка в один юнит — не рама, а плёнка, которую
движок считает, а глаз не видит.

Пропорциональная рама вдобавок не может развалиться по построению: рейке нужно,
чтобы сторона была больше 4a, стойке — чтобы высота была больше 5a, а само a не
больше меньшей стороны, делённой на 24. Проверено на десяти габаритах от 24 до
256: вырожденных кусков ноль.

ТЕКСТУРЫ. Панель — картинка ящика, правило «одна картинка на грань». Рама —
другой материал и общая сетка мира, без подгонки: он прямо сказал, что на
мелочь вроде реек не надо велосипедов с масштабами, нужна обычная текстура.

Шесть площадок — шесть пар «рама / панель». Задача человека: сказать, какая
пара выглядит как настоящий ящик.

    python3 tools/uvlab4.py [--png план.png] > /tmp/uvlab4.vmf
"""
