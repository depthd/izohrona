/* ЭТАЛОН ПО ЗАМЕРУ, а не по памяти.

   ЧЕМ БЫЛА ПЛОХА ПРЕДЫДУЩАЯ ВЕРСИЯ. Она считала скейл Source 2 как
   мой_скейл / 64 и радостно сообщала, что всё сходится с ящиками из Hammer.
   Но 64 — это ровно то число, которое она и должна была проверить: оно стояло
   в коде с v57, взятое по памяти. Проверка опиралась на проверяемое. Две ошибки
   сокращались (unit 32 с делителем 64 даёт тот же Source 2, что unit 128 с
   делителем 16), поэтому итог совпадал, а в .vmf уходило число вчетверо больше
   нужного — то самое «завышено», которое было видно в игре.

   ЗАМЕР. tools/uvruler.py печатает десять кубов 128x128x128 с разными uscale.
   После импорта в CS2:
     uscale 4  -> панель Tool Properties показывает 0.2500, на грани 128u два
                  ящика, то есть повтор 64 юнита;
     uscale 8  -> на грани 128u ровно ОДИН ящик, повтор 128 юнитов.
   Отсюда делитель = 16 и «скейл Source 2 = юнитов на тексель».
   Задним числом сходится и третье: грань 96u из сборки с подгонкой уходила со
   скейлом 24, панель показала 1.5 = 24/16.

   ПРОВЕРКА. Формула экспорта должна выдавать такие числа .vmf, чтобы после
   деления на 16 получились те самые textureScale, что стоят в ящиках,
   собранных руками (data/yashiki.vmap.txt).

     node tools/uvref.js
*/
const UVS  = 4;      // опорный скейл .vmf: 4/16 = 0.25 — дефолтная плотность редактора
const UNIT = 64;     // юнитов на повтор при UVS, для 256-текселя: 256 * 0.25
const IMP  = 16;     // ЗАМЕРЕНО линейкой: во столько импортёр делит скейл .vmf
const TEX  = 256;    // текселей в picrate1 — следует из «два ящика по 64u при 0.25»

/* n целых повторов на длину L, шов на ближнем крае c0 */
function fit(c0, L, reps){
  const sc  = L*UVS/(UNIT*reps);
  return {sc, off: -c0/sc};
}
const toS2 = f => ({sc: f.sc/IMP, off: f.off*IMP});
const mod = (a,m) => ((a%m)+m)%m;
const близко = (a,b,e) => Math.abs(a-b) < (e||1e-9);

/* Что стоит в ящиках, собранных руками. Смещения сверяются по модулю периода:
   сдвиг на целый повтор картинку не двигает, а Hammer пишет свёрнутое значение. */
const ЭТАЛОН = [
  { имя:'ящик 32u, грань +X (u по Y)',    c0: 3568, L:32, reps:1, sc:0.125,  off:128 },
  { имя:'ящик 32u, верх (v по -Y)',       c0:-3600, L:32, reps:1, sc:0.125,  off:128 },
  { имя:'ящик 32u, грань +Y (v по -Z)',   c0:  -32, L:32, reps:1, sc:0.125,  off:0   },
  { имя:'ящик 16u, грань +X (u по Y)',    c0: 3568, L:16, reps:1, sc:0.0625, off:0   },
  { имя:'ящик 16u, грань +Y (u по X)',    c0: 1488, L:16, reps:1, sc:0.0625, off:0   },
  { имя:'ящик 16u, грань +X (v по -Z)',   c0:  -16, L:16, reps:1, sc:0.0625, off:0   },
];
/* Что показала линейка. Здесь проверяется уже не формула, а сами константы. */
const ЛИНЕЙКА = [
  { имя:'куб 128u, uscale 4 -> панель 0.25, два ящика по 64u', vmf:4, s2:0.25, период:64  },
  { имя:'куб 128u, uscale 8 -> один ящик на грань 128u',       vmf:8, s2:0.5,  период:128 },
  { имя:'грань 96u из сборки с подгонкой -> панель 1.5',       vmf:24, s2:1.5, период:384 },
];

let плохо=0;
console.log('\n1. КОНСТАНТЫ ПРОТИВ ЛИНЕЙКИ\n');
for(const t of ЛИНЕЙКА){
  const s2=t.vmf/IMP, пер=TEX*s2;
  const ok=близко(s2,t.s2)&&близко(пер,t.период);
  if(!ok) плохо++;
  console.log(`  ${ok?'ок  ':'МИМО'}  ${t.имя}`);
  console.log(`         скейл ${s2} (замер ${t.s2}) · период ${пер}u (замер ${t.период}u)`);
}
console.log('\n2. ФОРМУЛА ЭКСПОРТА ПРОТИВ ЯЩИКОВ ИЗ HAMMER\n');
for(const t of ЭТАЛОН){
  const f=fit(t.c0,t.L,t.reps), s2=toS2(f);
  const okS=близко(s2.sc,t.sc), okO=близко(mod(s2.off,TEX),mod(t.off,TEX),1e-6);
  if(!okS||!okO) плохо++;
  console.log(`  ${okS&&okO?'ок  ':'МИМО'}  ${t.имя}`);
  console.log(`         .vmf скейл ${f.sc} -> Source 2 ${s2.sc} (в файле ${t.sc})`);
  console.log(`         .vmf сдвиг ${+f.off.toFixed(3)} -> Source 2 ${mod(s2.off,TEX)} (в файле ${mod(t.off,TEX)})`);
}
console.log('\n3. ЧТО ПОЛУЧАЕТ КАРТА ПО УМОЛЧАНИЮ\n');
console.log(`  скейл ${UVS} -> Source 2 ${UVS/IMP} -> ${1/(UVS/IMP)} пикселя на юнит,`+
            ` повтор ${TEX*UVS/IMP}u\n  (было ${8} -> ${8/IMP} -> ${1/(8/IMP)} пикс/юнит,`+
            ` повтор ${TEX*8/IMP}u, то есть вдвое крупнее нормы)`);
console.log(плохо? `\n  РАСХОЖДЕНИЙ: ${плохо}\n` : '\n  всё сходится\n');
process.exit(плохо?1:0);
