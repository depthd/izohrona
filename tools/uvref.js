/* ЭТАЛОН: два ящика, собранных руками в Hammer 2 и выгруженных в .vmap.
   Единственная ground truth по текстурам, какая у меня есть — CS2 отсюда не запустить.
   Скрипт считает по формуле экспорта и сверяет с тем, что записал сам Hammer.

   Что даёт файл yashiki.vmap:
     ящик 32u  ->  textureScale 0.125,   смещение по Y = 128 текселей
     ящик 16u  ->  textureScale 0.0625,  смещения нулевые
   На обоих — РОВНО ОДИН повтор текстуры на грань (проверено по texcoord:
   1440/32=45 и 1472/32=46, то есть ровно один шаг).

   Отсюда два числа, которых мне не хватало:
     picrate1 — 256 текселей, скейл Source 2 = ЮНИТОВ НА ТЕКСЕЛЬ,
       значит при скейле 0.125 повтор занимает 256*0.125 = 32 юнита;
     импортёр VMF делит скейл на 64 И УМНОЖАЕТ СМЕЩЕНИЕ на 64
       (VMF смещение 2 -> Source 2 смещение 128 — сходится на первом ящике).

     node tools/uvref.js
*/
const UVS  = 8;      // опорный скейл VMF, каким пишет экспорт
const UNIT = 32;     // юнитов на один повтор при скейле UVS (из vmap: 256px * 0.125)
const IMP  = 64;     // во сколько импортёр CS2 делит скейл и умножает смещение
const TEX  = 256;    // текселей в текстуре picrate1

/* Формула экспорта: n целых повторов на длину L, шов на ближнем крае c0. */
function fit(c0, L, reps){
  const sc  = L*UVS/(UNIT*reps);
  const off = -c0/sc;
  return {sc, off};
}
/* Как это увидит Source 2 после импорта. */
const toS2 = f => ({sc: f.sc/IMP, off: f.off*IMP});
/* Смещения сравниваются по модулю периода текстуры: сдвиг на целый повтор картинку
   не двигает, а Hammer пишет свёрнутое значение. */
const mod = (a,m) => ((a%m)+m)%m;
const близко = (a,b,e) => Math.abs(a-b) < (e||1e-6);

const ЭТАЛОН = [
  { имя:'ящик 32u, грань +X (u идёт по Y)', c0:3568, L:32, reps:1, sc:0.125,  off:128 },
  { имя:'ящик 32u, грань верх (v идёт по -Y)', c0:-3600, L:32, reps:1, sc:0.125, off:128 },
  { имя:'ящик 32u, грань +Y (v идёт по -Z)', c0:-32, L:32, reps:1, sc:0.125,  off:0   },
  { имя:'ящик 16u, грань +X (u идёт по Y)', c0:3568, L:16, reps:1, sc:0.0625, off:0   },
  { имя:'ящик 16u, грань +Y (u идёт по X)', c0:1488, L:16, reps:1, sc:0.0625, off:0   },
  { имя:'ящик 16u, грань +X (v идёт по -Z)', c0:-16, L:16, reps:1, sc:0.0625, off:0   },
];

let плохо=0;
console.log('\nсверка формулы экспорта с ящиками из Hammer 2\n');
for(const t of ЭТАЛОН){
  const s2 = toS2(fit(t.c0, t.L, t.reps));
  const okS = близко(s2.sc, t.sc, 1e-9);
  const okO = близко(mod(s2.off, TEX), mod(t.off, TEX), 1e-6);
  if(!okS||!okO) плохо++;
  console.log(`  ${okS&&okO?'ок  ':'МИМО'}  ${t.имя}`);
  console.log(`         скейл  ${s2.sc}  (Hammer ${t.sc})`);
  console.log(`         смещение ${mod(s2.off,TEX)}  (Hammer ${mod(t.off,TEX)})`);
}
/* Обратная проверка: сколько повторов ляжет на грань — должно выйти ровно 1. */
console.log('\n  повторов на грань:');
for(const t of [{L:32,reps:1},{L:16,reps:1},{L:96,reps:1},{L:288,reps:3}]){
  const f=fit(0,t.L,t.reps), период=UNIT*f.sc/UVS;
  console.log(`    грань ${t.L}u при ${t.reps} повтор(ах): период ${период}u, укладывается ${(t.L/период).toFixed(3)}`);
}
console.log(плохо? `\n  РАСХОЖДЕНИЙ: ${плохо}\n` : '\n  всё сходится\n');
process.exit(плохо?1:0);
