"""ГЕЙТ. Один прогон — один вердикт. Сборка не отдаётся, пока не зелено.

Смысл не в отчётности. Человек полтора десятка сессий работал тестовым харнесом:
открывал Хаммер, находил сломанное глазами, показывал пальцем. Каждый дефект,
который он находил так, ловится здесь одной командой за минуты. Пороги в
CLAUDE.md, они же продублированы ниже.

    python3 tools/priyomka.py [сборка] [карт]        # по умолчанию 3 карты
    python3 tools/priyomka.py builds/x.html 5 --быстро   # без крюка (он самый долгий)

Код возврата 0 — зелено, 1 — есть красное.
"""
import json, os, re, subprocess, sys, time

СБОРКА = 'builds/izohrona_v120.html'
КАРТ = 3
БЫСТРО = False
арг = [a for a in sys.argv[1:]]
if '--быстро' in арг:
    БЫСТРО = True
    арг.remove('--быстро')
if арг:
    СБОРКА = арг[0]
if len(арг) > 1:
    КАРТ = int(арг[1])
ПАПКА = '/tmp/gate'

# порог, направление ('<=' или '=='), человеческое имя
ПОРОГИ = {
    'пол против растра, клеток':      (0,   '=='),
    'плато паласа против растра':     (0,   '=='),
    'спавнов плохих':                 (0,   '=='),
    'цвет undefined':                 (0,   '=='),
    'вырожденных брашей':             (0,   '=='),
    'ошибок страницы':                (0,   '=='),
    'крюк: пар хуже x2':              (6,   '<='),
    'крюк: максимум':                 (4.0, '<='),
    'тел без опоры':                  (5,   '<='),
}


def прогон(cmd, тихо=False):
    t = time.time()
    r = subprocess.run(cmd, shell=True, capture_output=True, text=True)
    if not тихо:
        print(f'   … {time.time()-t:.0f}с')
    return r


печать = []
красное = []


def строка(имя, знач, порог=None):
    if порог is None:
        печать.append((имя, знач, '', ''))
        return
    предел, знак = порог
    ок = (знач == предел) if знак == '==' else (знач <= предел)
    if not ок:
        красное.append(имя)
    печать.append((имя, знач, f'{знак} {предел}', 'ок' if ок else 'КРАСНОЕ'))


print(f'\nГЕЙТ · {СБОРКА} · карт {КАРТ}\n')

# ---- 1. синтаксис ----
print('1. синтаксис')
r = прогон('python3 tools/syncheck.py && node --check /tmp/build.js')
строка('синтаксис', 'ок' if r.returncode == 0 else 'ПАДАЕТ',
       (0, '==') if False else None)
if r.returncode != 0:
    красное.append('синтаксис')
    print(r.stderr[-600:])
    print('\nдальше нет смысла: файл не разбирается')
    sys.exit(1)

# ---- 2. константы текстур против замера ----
print('2. константы текстур (uvref)')
r = прогон('node tools/uvref.js')
строка('текстуры: константы против линейки', 'сходятся' if r.returncode == 0 else 'РАСХОДЯТСЯ')
if r.returncode != 0:
    красное.append('текстуры: константы')

# ---- 3. смоук ----
print('3. смоук продукта')
r = прогон(f'node tools/smoke.js {СБОРКА}')
прошёл = 'ВСЁ ПРОШЛО' in r.stdout
строка('смоук', 'пройден' if прошёл else 'УПАЛ')
if not прошёл:
    красное.append('смоук')
    print('\n'.join(l for l in r.stdout.splitlines() if 'ПЛОХО' in l or 'нет' in l)[:800])

# ---- 4. сборка карт ----
print(f'4. сборка {КАРТ} карт')
r = прогон(f'node tools/gate_export.js {СБОРКА} {КАРТ} {ПАПКА}', тихо=True)
sys.stderr.write(r.stderr)
gen = json.load(open(f'{ПАПКА}/gen.json', encoding='utf-8'))
карты = gen['карты']
файлы = [c['файл'] for c in карты]

строка('карт собрано', len(карты))
строка('ошибок страницы', len(gen['ошибкиСтраницы']), ПОРОГИ['ошибок страницы'])
строка('пол против растра, клеток',
       max(c['surf']['расходятся'] for c in карты), ПОРОГИ['пол против растра, клеток'])
строка('плато паласа против растра',
       max((c.get('palas') or {}).get('расходятся', 0) for c in карты),
       ПОРОГИ['плато паласа против растра'])
строка('карт с паласом', sum(1 for c in карты if (c.get('palas') or {}).get('плато')))
строка('экспорт закрыл пола, %',
       max((c.get('block') or {}).get('доля', 0) for c in карты))
строка('вырожденных брашей', max(c['degen'] for c in карты), ПОРОГИ['вырожденных брашей'])
строка('цвет undefined', max(c['цветUndefined'] for c in карты), ПОРОГИ['цвет undefined'])
строка('спавнов T+CT (минимум по картам)', min(c['спавновT'] + c['спавновC'] for c in карты))
строка('мест на карту', f"{min(c['мест'] for c in карты)}..{max(c['мест'] for c in карты)}")
строка('каллаутов', f"{min(c['каллаутов'] for c in карты)}..{max(c['каллаутов'] for c in карты)}")
строка('брашей', f"{min(c['брашей'] for c in карты)}..{max(c['брашей'] for c in карты)}")
строка('сборка .vmf, с', f"{min(c['мс'] for c in карты)/1000:.1f}..{max(c['мс'] for c in карты)/1000:.1f}")

# ---- 5. спавны и висящие тела ----
print('5. спавны и опора тел')
плохСпавн, висело = 0, 0
for f in файлы:
    r = прогон(f'python3 tools/vise.py {f}', тихо=True)
    o = r.stdout
    m = re.search(r'=== СПАВНЫ \((\d+)\) ===\n(.*?)\n\n', o, re.S)
    if m:
        всего = int(m.group(1))
        окн = re.search(r'^\s*(\d+)\s+ок$', m.group(2), re.M)
        плохСпавн = max(плохСпавн, всего - (int(окн.group(1)) if окн else 0))
    m2 = re.search(r'тел без опоры[^:]*:\s*(\d+)', o)
    if m2:
        висело = max(висело, int(m2.group(1)))
print(f'   … готово')
строка('спавнов плохих', плохСпавн, ПОРОГИ['спавнов плохих'])
строка('тел без опоры', висело, ПОРОГИ['тел без опоры'])

# ---- 6. крюк ----
if БЫСТРО:
    строка('крюк', 'пропущен (--быстро)')
else:
    сколько = min(2, len(файлы))
    print(f'6. крюк между соседними каллаутами ({сколько} карты, это долго)')
    r = прогон('python3 tools/krjuk.py ' + ' '.join(файлы[:сколько]), тихо=True)
    хуже = [int(x) for x in re.findall(r'хуже 2\.0: (\d+)', r.stdout)]
    макс = [float(x) for x in re.findall(r'максимум ([\d.]+)', r.stdout)]
    мед = [float(x) for x in re.findall(r'медиана ([\d.]+)', r.stdout)]
    print(f'   … готово')
    if хуже:
        строка('крюк: медиана', f'{min(мед):.2f}..{max(мед):.2f}')
        строка('крюк: пар хуже x2', max(хуже), ПОРОГИ['крюк: пар хуже x2'])
        строка('крюк: максимум', max(макс), ПОРОГИ['крюк: максимум'])
        for ln in r.stdout.splitlines():
            if 'БАРИКАДА' in ln:
                печать.append(('  ' + ln.strip()[:70], '', '', ''))
    else:
        строка('крюк', 'НЕ ПОСЧИТАН')
        красное.append('крюк')

# ---- вердикт ----
ш = max(len(str(a)) for a, _, _, _ in печать) + 2
print('\n' + '─' * (ш + 34))
for имя, знач, порог, вер in печать:
    print(f'{имя:<{ш}} {str(знач):>10}  {порог:<8} {вер}')
print('─' * (ш + 34))
if красное:
    print(f'\nКРАСНОЕ: {", ".join(красное)}\nОтдавать нельзя.\n')
    sys.exit(1)
print('\nЗЕЛЕНО. Можно отдавать.\n')
