      '\t"bShowGrid" "1"\n\t"nGridSpacing" "64"\n}\n'
      f'world\n{{\n\t"id" "{wid}"\n\t"mapversion" "1"\n'
      '\t"classname" "worldspawn"\n\t"skyname" "sky_dust"\n'
