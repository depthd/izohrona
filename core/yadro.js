'use strict';
/* ЯДРО ИЗ ВЕЩЕЙ — черновик, шаг 1.

   Карта — это список вещей с размерами в юнитах: помещения, стены, проёмы,
   предметы, точки. Вещь знает соседей: стена — оба помещения по бокам, проём —
   свою стену, рама — свой проём или свой ящик. Всё ставится через ОДНУ
   диспетчерскую, которая знает, что где стоит: конфликт ловится в момент
   постановки, а не проверкой после. Геометрия для Hammer, снимок для замеров и
   картинки ВЫВОДЯТСЯ из вещей и обратно в них ничего не пишут, поэтому
   разойтись с картой не могут.

   Почему так, а не клетками — см. CLAUDE.md, правила 4, 4.1, 5, 5.2, 5.4, 5.5:
   все они про то, что этап добавлял своё и не сообщал остальным. */

const ИГРОК = { ширина: 32, рост: 72 };
const ЩЕЛЬ = 96;          // между вещами либо вплотную, либо не уже этого (порог гейта)
const ПРИДВЕРЬЕ = 64;     // глубина места перед дверью, где ничего не ставится

const прям = (x0, y0, x1, y1) => ({ x0, y0, x1, y1 });
const внахлёст = (a, b) => a.x0 < b.x1 && b.x0 < a.x1 && a.y0 < b.y1 && b.y0 < a.y1;
const внутри = (a, b) => a.x0 >= b.x0 && a.x1 <= b.x1 && a.y0 >= b.y0 && a.y1 <= b.y1;
/* Ширина прохода между двумя прямоугольниками: по одной оси, если они друг
   напротив друга, иначе от угла до угла. Отрицательная — значит внахлёст. */
function просвет(a, b) {
  const dx = Math.max(b.x0 - a.x1, a.x0 - b.x1), dy = Math.max(b.y0 - a.y1, a.y0 - b.y1);
  return dx > 0 && dy > 0 ? Math.hypot(dx, dy) : Math.max(dx, dy);
}

class Карта {
  constructor() {
    this.помещения = []; this.стены = []; this.проёмы = []; this.вещи = []; this.точки = [];
    this.журнал = [];
  }

  помещение(имя, x0, y0, x1, y1, о = {}) {
    const п = { вид: 'помещение', имя, прям: прям(x0, y0, x1, y1), z: о.z || 0, пол: о.пол };
    this.помещения.push(п);
    return п;
  }

  /* Стена сама находит, что у неё по бокам. */
  стена(x0, y0, x1, y1, о = {}) {
    const с = { вид: 'стена', прям: прям(x0, y0, x1, y1), высота: о.высота || 192, мат: о.мат,
                ось: (x1 - x0) >= (y1 - y0) ? 'x' : 'y', проёмы: [] };
    с.толщина = с.ось === 'x' ? y1 - y0 : x1 - x0;
    const касается = п => {
      const r = п.прям;
      return с.ось === 'x'
        ? (r.y1 === y0 || r.y0 === y1) && r.x0 < x1 && x0 < r.x1
        : (r.x1 === x0 || r.x0 === x1) && r.y0 < y1 && y0 < r.y1;
    };
    с.стороны = this.помещения.filter(касается);
    this.стены.push(с);
    return с;
  }

  /* Проём — интервал на стене. Рама живёт ВНУТРИ проёма, а не поверх стены. */
  проём(с, вид, от, до, о = {}) {
    const р = { вид, стена: с, от, до, низ: о.низ || 0, верх: о.верх || 128, рама: о.рама || 0 };
    const [a0, a1] = с.ось === 'x' ? [с.прям.x0, с.прям.x1] : [с.прям.y0, с.прям.y1];
    if (от < a0 || до > a1) return this.отказ(вид, 'вылезает за стену');
    if (с.проёмы.some(q => от < q.до && q.от < до)) return this.отказ(вид, 'наезжает на другой проём');
    if (вид === 'дверь' && с.стороны.length < 2) return this.отказ(вид, 'за стеной нет пола');
    р.чистая = (до - от) - 2 * р.рама;
    if (вид === 'дверь' && р.чистая < ЩЕЛЬ) return this.отказ(вид, `проход ${р.чистая}u уже ${ЩЕЛЬ}u`);
    с.проёмы.push(р);
    this.проёмы.push(р);
    this.журнал.push(`${вид}: поставлен, ширина в свету ${р.чистая}u`);
    return р;
  }

  отказ(что, почему) { this.журнал.push(`${что}: НЕ поставлен — ${почему}`); return null; }

  /* Перед дверью ничего не ставится: зона глубиной ПРИДВЕРЬЕ по обе стороны. */
  придверья() {
    const out = [];
    for (const р of this.проёмы) if (р.вид === 'дверь') {
      const r = р.стена.прям;
      if (р.стена.ось === 'x') { out.push(прям(р.от, r.y0 - ПРИДВЕРЬЕ, р.до, r.y0), прям(р.от, r.y1, р.до, r.y1 + ПРИДВЕРЬЕ)); }
      else { out.push(прям(r.x0 - ПРИДВЕРЬЕ, р.от, r.x0, р.до), прям(r.x1, р.от, r.x1 + ПРИДВЕРЬЕ, р.до)); }
    }
    return out;
  }

  твёрдое(кроме) {
    return [...this.стены.map(с => ({ имя: 'стена', прям: с.прям })),
            ...this.вещи.filter(в => в !== кроме).map(в => ({ имя: в.имя, прям: в.след }))];
  }

  /* ДИСПЕТЧЕРСКАЯ. Возвращает причину отказа или null. */
  почему_нельзя(след) {
    if (!this.помещения.some(п => внутри(след, п.прям))) return 'не на полу';
    for (const т of this.твёрдое()) if (внахлёст(след, т.прям)) return 'занято: ' + т.имя;
    for (const з of this.придверья()) if (внахлёст(след, з)) return 'перекрыл бы дверь';
    for (const т of this.твёрдое()) {
      const g = просвет(след, т.прям);
      if (g > 0 && g < ЩЕЛЬ) return `оставил бы щель ${Math.round(g)}u до «${т.имя}»`;
    }
    return null;
  }

  /* Ящик с рамой по схеме из data/yashiki-borta.md: тело c, рама из одного числа
     a = c/24, наружный габарит c + 4a. Если ящик оставляет щель — диспетчерская
     пробует придвинуть его вплотную и только потом отказывает. */
  ящик(имя, x, y, c, о = {}) {
    const a = c / 24, s = c + 4 * a;
    let след = прям(x, y, x + s, y + s);
    let why = this.почему_нельзя(след);
    if (why && why.startsWith('оставил бы щель') && о.придвинуть !== false) {
      for (const т of this.твёрдое()) {
        const g = просвет(след, т.прям);
        if (!(g > 0 && g < ЩЕЛЬ)) continue;
        const r = т.прям;
        const dx = r.x0 >= след.x1 ? g : r.x1 <= след.x0 ? -g : 0;
        const dy = r.y0 >= след.y1 ? g : r.y1 <= след.y0 ? -g : 0;
        const c2 = прям(след.x0 + dx, след.y0 + dy, след.x1 + dx, след.y1 + dy);
        if (!this.почему_нельзя(c2)) {
          this.журнал.push(`${имя}: оставлял щель ${Math.round(g)}u — придвинут вплотную к «${т.имя}»`);
          след = c2; why = null; break;
        }
      }
    }
    if (why) return this.отказ(имя, why);
    const в = { вид: 'ящик', имя, след, c, a, z: о.z || 0 };
    this.вещи.push(в);
    if (!this.журнал.some(s2 => s2.startsWith(имя + ':'))) this.журнал.push(`${имя}: поставлен`);
    return в;
  }

  точка(cls, x, y, о = {}) {
    const след = прям(x - 16, y - 16, x + 16, y + 16);
    const why = this.почему_нельзя(след);
    if (why) return this.отказ(cls, why);
    const т = { cls, at: [x, y, (о.z || 0) + 8], angles: о.angles || [0, 0, 0] };
    this.точки.push(т);
    return т;
  }

  /* ===== ВСЁ НИЖЕ ВЫВОДИТСЯ ИЗ ВЕЩЕЙ ===== */

  геометрия(мат) {
    const boxes = [];
    const B = (x0, y0, z0, x1, y1, z1, m, tex, роль) => {
      if (x1 > x0 && y1 > y0 && z1 > z0) boxes.push({ x0, y0, z0, x1, y1, z1, mat: m, tex: tex || { rule: 'мир' }, роль });
    };
    for (const п of this.помещения) { const r = п.прям; B(r.x0, r.y0, п.z - 16, r.x1, r.y1, п.z, п.пол || мат.пол, null, 'пол'); }
    for (const с of this.стены) {
      const r = с.прям, h = с.высота, m = с.мат || мат.стена;
      // стена вдоль оси: участок [u0,u1] на высоте [z0,z1]
      const кусок = (u0, u1, z0, z1, mm, роль) => с.ось === 'x' ? B(u0, r.y0, z0, u1, r.y1, z1, mm, null, роль)
                                                                : B(r.x0, u0, z0, r.x1, u1, z1, mm, null, роль);
      const [a0, a1] = с.ось === 'x' ? [r.x0, r.x1] : [r.y0, r.y1];
      let u = a0;
      for (const р of [...с.проёмы].sort((p, q) => p.от - q.от)) {
        кусок(u, р.от, -16, h, m, 'стена');
        const подНогами = р.вид === 'дверь' ? (с.стороны[0] && с.стороны[0].пол) || мат.пол : m;
        кусок(р.от, р.до, -16, р.низ, подНогами, 'стена');
        кусок(р.от, р.до, р.верх, h, m, 'стена');
        if (р.рама) {
          const k = р.рама, mr = мат.рама;
          кусок(р.от, р.от + k, р.низ, р.верх, mr, 'рама');
          кусок(р.до - k, р.до, р.низ, р.верх, mr, 'рама');
          кусок(р.от + k, р.до - k, р.верх - k, р.верх, mr, 'рама');
          if (р.низ > 0) кусок(р.от + k, р.до - k, р.низ, р.низ + k, mr, 'рама');
        }
        u = р.до;
      }
      кусок(u, a1, -16, h, m, 'стена');
    }
    for (const в of this.вещи) if (в.вид === 'ящик') {
      const { c, a, z } = в, X = в.след.x0 + 2 * a, Y = в.след.y0 + 2 * a;   // тело утоплено на вылет рамы
      B(X, Y, z, X + c, Y + c, z + c, мат.ящик, { rule: 'грань', size: 256 }, 'тело');
      for (const [x0, y0, z0, x1, y1, z1] of рамаЯщика(c, a))
        B(X + x0, Y + y0, z + z0, X + x1, Y + y1, z + z1, мат.рамаЯщика, null, 'рама');
    }
    return boxes;
  }

  /* Снимок для замеров: где может стоять игрок. Сетка 8u, считается заново из
     вещей каждый раз — в неё никто не пишет. */
  снимок(шаг = 8) {
    const всё = [...this.помещения.map(п => п.прям), ...this.стены.map(с => с.прям)];
    const X0 = Math.min(...всё.map(r => r.x0)), Y0 = Math.min(...всё.map(r => r.y0));
    const W = Math.ceil((Math.max(...всё.map(r => r.x1)) - X0) / шаг), H = Math.ceil((Math.max(...всё.map(r => r.y1)) - Y0) / шаг);
    const пол = new Uint8Array(W * H);
    const залить = (r, v) => {
      for (let y = Math.max(0, Math.floor((r.y0 - Y0) / шаг)); y < Math.min(H, Math.ceil((r.y1 - Y0) / шаг)); y++)
        for (let x = Math.max(0, Math.floor((r.x0 - X0) / шаг)); x < Math.min(W, Math.ceil((r.x1 - X0) / шаг)); x++) пол[y * W + x] = v;
    };
    for (const п of this.помещения) залить(п.прям, 1);
    for (const с of this.стены) залить(с.прям, 0);
    for (const р of this.проёмы) if (р.вид === 'дверь') {
      const r = р.стена.прям, k = р.рама;
      залить(р.стена.ось === 'x' ? прям(р.от + k, r.y0, р.до - k, r.y1) : прям(r.x0, р.от + k, r.x1, р.до - k), 1);
    }
    for (const в of this.вещи) залить(в.след, 0);
    // где помещается квадрат шириной w: суммы по префиксу
    const S = new Int32Array((W + 1) * (H + 1));
    for (let y = 0; y < H; y++) for (let x = 0; x < W; x++)
      S[(y + 1) * (W + 1) + x + 1] = пол[y * W + x] + S[y * (W + 1) + x + 1] + S[(y + 1) * (W + 1) + x] - S[y * (W + 1) + x];
    const влезает = w => {
      const r = Math.ceil(w / 2 / шаг), out = new Uint8Array(W * H);
      for (let y = r; y < H - r; y++) for (let x = r; x < W - r; x++) {
        const s = S[(y + r) * (W + 1) + x + r] - S[(y - r) * (W + 1) + x + r] - S[(y + r) * (W + 1) + x - r] + S[(y - r) * (W + 1) + x - r];
        if (s === 4 * r * r) out[y * W + x] = 1;
      }
      return out;
    };
    const волна = (m, sx, sy) => {
      const seen = new Uint8Array(W * H), q = [];
      const s = Math.floor((sy - Y0) / шаг) * W + Math.floor((sx - X0) / шаг);
      if (!m[s]) return seen;
      seen[s] = 1; q.push(s);
      while (q.length) {
        const i = q.pop(), x = i % W, y = (i / W) | 0;
        for (const [dx, dy] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) {
          const nx = x + dx, ny = y + dy, j = ny * W + nx;
          if (nx >= 0 && ny >= 0 && nx < W && ny < H && m[j] && !seen[j]) { seen[j] = 1; q.push(j); }
        }
      }
      return seen;
    };
    return { W, H, X0, Y0, шаг, пол, влезает, волна };
  }

  /* Приёмка черновика: до каждого помещения можно дойти от T-спавна, и дойти
     проходом не уже ЩЕЛЬ — то, что старый гейт искал после, здесь по построению. */
  приёмка() {
    const сн = this.снимок();
    const T = this.точки.find(т => т.cls === 'info_player_terrorist');
    const out = [];
    for (const [w, имя] of [[ИГРОК.ширина, 'игрок проходит'], [ЩЕЛЬ, `проход не уже ${ЩЕЛЬ}u`]]) {
      const m = сн.влезает(w), seen = сн.волна(m, T.at[0], T.at[1]);
      const нет = this.помещения.filter(п => {
        for (let y = 0; y < сн.H; y++) for (let x = 0; x < сн.W; x++) {
          const px = сн.X0 + (x + 0.5) * сн.шаг, py = сн.Y0 + (y + 0.5) * сн.шаг, r = п.прям;
          if (seen[y * сн.W + x] && px > r.x0 && px < r.x1 && py > r.y0 && py < r.y1) return false;
        }
        return true;
      });
      out.push(`${имя}: ${нет.length ? 'НЕ доходит до ' + нет.map(п => п.имя).join(', ') : 'до всех помещений'}`);
    }
    return out;
  }
}

/* 21 кусок рамы в координатах тела [0,c]^3 — его схема из yashiki-borta.md,
   записанная через одно число a. Низ и верх разные: снизу пол, торчать нельзя. */
function рамаЯщика(c, a) {
  const out = [];
  const mir = (r, ax) => { const q = r.slice(); q[ax] = c - r[ax + 3]; q[ax + 3] = c - r[ax]; return q; };
  const all4 = r => [r, mir(r, 0), mir(r, 1), mir(mir(r, 0), 1)];
  out.push(...all4([-2 * a, -2 * a, 0, 2 * a, 2 * a, 3 * a]));             // углы низ
  out.push(...all4([-2 * a, -2 * a, c - 2 * a, 2 * a, 2 * a, c + 2 * a]));   // углы верх
  out.push(...all4([-a, -a, 3 * a, 2 * a, 2 * a, c - 2 * a]));               // стойки
  const рейки = (z0, z1) => {
    const rx = [-a, 2 * a, z0, 2 * a, c - 2 * a, z1];                         // вдоль Y у грани x=0
    const ry = [2 * a, -a, z0, c - 2 * a, 2 * a, z1];                         // вдоль X у грани y=0
    out.push(rx, mir(rx, 0), ry, mir(ry, 1));
  };
  рейки(0, 3 * a);
  рейки(c - 2 * a, c + a);
  return out;
}

module.exports = { Карта, рамаЯщика, ИГРОК, ЩЕЛЬ };
